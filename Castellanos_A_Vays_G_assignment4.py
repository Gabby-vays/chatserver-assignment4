def canon(u: str) -> str:
    return u.strip().lower()

# ---------------------- ROOM MANAGEMENT ----------------------

@dataclass
class Room:
    id: int
    topic: str
    leader: str
    members: set[str] = field(default_factory=set)

class State:
    def __init__(self):
        self._lock = RLock()
        self.rooms: dict[int, Room] = {}
        self.online_users: dict[str, socket] = {}
        self._next_room_id = 1

    def new_room(self, topic: str, leader: str) -> int:
        with self._lock:
            rid = self._next_room_id
            self._next_room_id += 1
            self.rooms[rid] = Room(rid, topic, leader, {leader})
            return rid

    def list_rooms(self):
        with self._lock:
            return [
                f"{rid}: {r.topic} | leader={r.leader} | members={len(r.members)}"
                for rid, r in sorted(self.rooms.items())
            ]

    def join_room(self, rid: int, user: str):
        with self._lock:
            if rid not in self.rooms:
                return False
            self.rooms[rid].members.add(user)
            return True

    def leave_room(self, rid: int, user: str):
        with self._lock:
            if rid not in self.rooms:
                return None
            r = self.rooms[rid]
            if user not in r.members:
                return None
            r.members.remove(user)
            leader_left = (user == r.leader)
            if leader_left:
                members = r.members.copy()
                del self.rooms[rid]
                return members
            return set()

    def broadcast_to_room(self, rid: int, sender: str, msg: str):
        with self._lock:
            room = self.rooms.get(rid)
            if not room:
                return False
            full_msg = f"[{rid}] {sender}: {msg}"
            for member in room.members:
                if member == sender:
                    continue
                # skip if receiver has blocked sender
                if canon(sender) in blocked_users.get(canon(member), set()):
                    continue
                member_sock = self.online_users.get(member)
                if member_sock:
                    safe_send_line(member_sock, full_msg)
                    safe_send_line(member_sock, f"<{member}:> ")
                else:
                    print(f"[DEBUG] no socket found for {member}")
        return True

STATE = State()

